'use strict';
const fs=require('fs'),{chromium}=require('playwright');
const template=fs.readFileSync('views/community.ejs','utf8');
const dialog=template.match(/<dialog id="community-preview-panel"[^]*?<\/dialog>/)[0];
const script=fs.readFileSync('public/static/js/community.js','utf8');
const handlers=script.slice(script.indexOf("    $('preview-close').addEventListener"),script.indexOf("    $('delete').addEventListener",script.indexOf("    $('preview-close').addEventListener")));
let browser,page;
beforeAll(async()=>{browser=await chromium.launch({channel:'chrome',headless:true});});
afterAll(async()=>browser?.close());
afterEach(async()=>page?.close());
test.each([390,1200])('article preview is a dismissible modal at %s px',async width=>{
 page=await browser.newPage({viewport:{width,height:800}});
 await page.setContent('<style>:root{--bs-body-bg:white;--bs-body-color:#222}body{margin:0}button{padding:10px}.btn-close:after{content:"×"}</style><main class="community"><form id="community-editor-form"><input id="community-title" value="Unsaved title"><input id="community-subtitle" value="Subtitle"><input id="community-cover-url"><input id="community-kind" value="article"><textarea id="community-markdown">Unsaved body العربية</textarea></form><button id="community-preview-button">Preview</button><button id="community-publish">Publish</button>'+dialog+'</main>');
 await page.addStyleTag({path:'public/static/css/community.css'});
 await page.addStyleTag({path:'public/static/css/markdown-content.css'});
 await page.evaluate(handlers=>{
  window.$=id=>document.getElementById('community-'+id);
  window.signature=()=>$('markdown').value;window.previewSignature=null;
  window.api=async(_path,_method,body)=>{window.requested=body;return {html:'<p>'+body.markdown+'</p>'};};
  window.run=async(fn,button)=>{button.disabled=true;try{await fn();}finally{button.disabled=false;}};
  (0,eval)(handlers);
 },handlers);
 await page.getByRole('button',{name:'Preview',exact:true}).click();
 expect(await page.locator('dialog').evaluate(el=>el.matches(':modal'))).toBe(true);
 expect(await page.locator('#community-preview').innerText()).toBe('Unsaved body العربية');
 expect(await page.evaluate(()=>requested)).toEqual({markdown:'Unsaved body العربية',kind:'article'});
 const box=await page.locator('dialog').boundingBox();
 expect(box.x).toBeGreaterThanOrEqual(0);expect(box.x+box.width).toBeLessThanOrEqual(width);
 await page.screenshot({path:'/tmp/article-preview-modal-'+width+'.png'});
 await page.keyboard.press('Escape');
 expect(await page.locator('dialog').isVisible()).toBe(false);
 expect(await page.evaluate(()=>document.activeElement.id)).toBe('community-preview-button');
 await page.locator('textarea').fill('Updated unsaved body');
 await page.getByRole('button',{name:'Preview',exact:true}).click();
 expect(await page.locator('#community-preview').innerText()).toBe('Updated unsaved body');
 await page.getByRole('button',{name:'Close preview'}).click();
 expect(await page.locator('dialog').isVisible()).toBe(false);
 await page.getByRole('button',{name:'Preview',exact:true}).click();
 await page.mouse.click(1,1);
 expect(await page.locator('dialog').isVisible()).toBe(false);
 expect(await page.locator('textarea').inputValue()).toBe('Updated unsaved body');
});
