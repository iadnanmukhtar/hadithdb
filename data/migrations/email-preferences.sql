CREATE TABLE IF NOT EXISTS email_preferences (
  email_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  unsubscribe_token CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
  enabled TINYINT NOT NULL DEFAULT 1,
  likes TINYINT NOT NULL DEFAULT 1,
  reflections TINYINT NOT NULL DEFAULT 1,
  replies TINYINT NOT NULL DEFAULT 1,
  reactions TINYINT NOT NULL DEFAULT 1,
  articles TINYINT NOT NULL DEFAULT 1,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
