CREATE TABLE IF NOT EXISTS community_authors (
 uid VARCHAR(128) COLLATE utf8mb4_bin PRIMARY KEY,
 handle VARCHAR(40) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL, bio VARCHAR(1000) NOT NULL DEFAULT '',
 email VARCHAR(320) NULL, trusted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_posts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, author_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 kind VARCHAR(12) NOT NULL, title VARCHAR(240) NOT NULL, markdown MEDIUMTEXT NOT NULL, tags VARCHAR(500) NOT NULL DEFAULT '',
 status VARCHAR(16) NOT NULL DEFAULT 'draft', version INT NOT NULL DEFAULT 1,
 public_title VARCHAR(240) NULL, public_markdown MEDIUMTEXT NULL, public_tags VARCHAR(500) NULL,
 notify_email TINYINT NOT NULL DEFAULT 0,
 published_at DATETIME(3) NULL, updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX community_posts_wall (status, published_at, id), INDEX community_posts_author (author_uid, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, post_id BIGINT UNSIGNED NOT NULL,
 version INT NOT NULL, title VARCHAR(240) NOT NULL, markdown MEDIUMTEXT NOT NULL, tags VARCHAR(500) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), UNIQUE KEY community_revision (post_id, version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_follows (
 follower_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL, author_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 email_enabled TINYINT NOT NULL DEFAULT 0, unsubscribe_token CHAR(64) CHARACTER SET ascii NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY (follower_uid, author_uid), UNIQUE KEY (unsubscribe_token), INDEX (author_uid, email_enabled)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_comments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, post_id BIGINT UNSIGNED NOT NULL,
 parent_id BIGINT UNSIGNED NULL, author_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 markdown TEXT NOT NULL, deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX (post_id, created_at), INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reporter_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 post_id BIGINT UNSIGNED NOT NULL, comment_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 reason VARCHAR(1000) NOT NULL, resolved TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), UNIQUE KEY (reporter_uid, post_id, comment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_email_outbox (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, post_id BIGINT UNSIGNED NOT NULL,
 follower_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'queued',
 attempts INT NOT NULL DEFAULT 0, available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 locked_at DATETIME(3) NULL, sent_at DATETIME(3) NULL,
 UNIQUE KEY (post_id, follower_uid), INDEX (status, available_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS community_likes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 source VARCHAR(32) NOT NULL, target_id BIGINT UNSIGNED NOT NULL,
 user_uid VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY community_like_user (source, target_id, user_uid), INDEX community_like_feed (created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
